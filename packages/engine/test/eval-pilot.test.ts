/**
 * RULING 1 AND S7 — THE PILOT MEASURES, AND ITS ARITHMETIC COMES FROM THE CODE.
 *
 * S7, in the reviewer's words: *"Counted end-to-end with a counting backend
 * through `runAb` (64 beings/arm, 2 arms, one seed, ticks 800): **918 calls**,
 * 7.17 thinks/being … so block (b) is priced by a tick count the README never
 * states. Thinks per being are a function of TICKS and the trait cadence —
 * nothing in `AbSpec` caps them."* The README said 1,024.
 *
 * Ruling 1: *"The pilot is ESTIMATION, not confirmation. Four rounds of
 * squeezing a verdict out of ≤ 2,000 calls keep producing flattering maths. A
 * pilot's job is to MEASURE the nuisance parameters the confirmatory design
 * needs."* The artefact's `usableForVerdict` is the literal `false`, and this
 * file holds the type to it as well as the value.
 */

const README = fileURLToPath(new URL('../src/eval/README.md', import.meta.url));

/** Every integer in the README's pilot table, so a stale number cannot hide. */
function pilotNumbersInReadme(): Set<number> {
  const text = readFileSync(README, 'utf8');
  const start = text.indexOf('<!-- DRY-RUN TABLE: generated by dryRunPilot() -->');
  const end = text.indexOf('<!-- END DRY-RUN TABLE -->');
  expect(start, 'the README must carry the generated dry-run table').toBeGreaterThan(-1);
  expect(end).toBeGreaterThan(start);
  const block = text.slice(start, end);
  return new Set([...block.matchAll(/\b(\d[\d,]*)\b/g)].map((m) => Number(m[1]!.replace(/,/g, ''))));
}

function render(table: PilotCallTable): string {
  const rows = table.blocks.map((b) => `| ${b.id} | ${b.what} | **${b.calls}** |`);
  return [
    '| # | block | calls |',
    '|---|---|---|',
    ...rows,
    `| — | retry head-room (${table.recipe.retryHeadRoomRate * 100}% of the blocks that go through LlmMind) | **${table.retryHeadRoom}** |`,
    `| | **total** | **${table.total}** |`,
    `| | reserve against a ${table.budgetLimit}-call budget | **${table.reserve}** |`,
    '',
    `Measured thinks per being at ${table.recipe.ticks} ticks: **${table.thinksPerBeing}**.`,
  ].join('\n');
}

describe('W1-E · S7 · the pilot arithmetic comes from the code, not the README', () => {
  let table: PilotCallTable;

  it('executes the EXACT pilot path with a counting backend and prints calls per block', async () => {
    table = await dryRunPilot();
    // eslint-disable-next-line no-console
    console.log(['', 'S7 · dryRunPilot():', render(table)].join('\n'));
    expect(table.blocks.map((b) => b.id)).toEqual(['a', 'a2', 'b', 'b2']);
    // Every block is a real count, not a product of two hopes.
    for (const block of table.blocks) expect(block.calls).toBeGreaterThan(0);
    expect(table.subtotal).toBe(table.blocks.reduce((s, b) => s + b.calls, 0));
    expect(table.total).toBe(table.subtotal + table.retryHeadRoom);
    expect(table.fits).toBe(true);
    // THINKS PER BEING IS MEASURED. Round 4 asserted 8 and the truth was 7.17.
    expect(table.thinksPerBeing).toBeGreaterThan(0);
  }, 1_800_000);

  it('pins the README to that output — a stale table fails here', async () => {
    const measured = table ?? (await dryRunPilot());
    const inReadme = pilotNumbersInReadme();
    const mustAppear = [
      ...measured.blocks.map((b) => b.calls),
      measured.retryHeadRoom,
      measured.total,
      measured.reserve,
      measured.budgetLimit,
      measured.recipe.seeds,
      measured.recipe.cohortSize,
      measured.recipe.ticks,
    ];
    const missing = mustAppear.filter((n) => !inReadme.has(n));
    expect(missing, `the README's pilot table is stale: ${missing.join(', ')} are not in it`).toEqual([]);
  }, 1_800_000);

  it('caps thinks by the budget, so ticks can never silently exceed the plan', async () => {
    const measured = table ?? (await dryRunPilot());
    const allowance = allowanceFor(measured);
    const traceBlock = measured.blocks.find((b) => b.id === 'b')!.calls;
    expect(allowance).toBeGreaterThanOrEqual(traceBlock);
    // …and a plan that under-prices itself HALTS rather than overrunning.
    const { runAb } = await import('../src/eval/ab.js');
    const halted = await runAb(
      {
        seeds: ['allowance'],
        ticks: 900,
        cohortSize: 4,
        agentCount: 16,
        callAllowance: 3,
        blindSecret: 'allowance-secret-0123456789abcde',
      },
      { arms: [{ id: 'A', backend: { kind: 'mock', mind: 'faithful' } }, { id: 'B', backend: { kind: 'mock', mind: 'omniscient' } }] },
      'population',
    );
    expect(halted.usable).toBe(false);
    if (!halted.usable) {
      expect(halted.reason).toBe('allowance-exceeded');
      expect(halted.detail).toMatch(/the plan allowed 3/);
      // NO verdict fields at all on a halted run.
      expect('contrasts' in halted).toBe(false);
      expect('traces' in halted).toBe(false);
    }
  }, 1_800_000);
});

describe('W1-E · ruling 1 · the pilot is ESTIMATION, and cannot print a verdict', () => {
  let artefact: PilotArtefact;

  it('returns an artefact whose usableForVerdict is false BY CONSTRUCTION', async () => {
    const run = await runPilotEstimation();
    expect(run.artefact).not.toBeNull();
    artefact = run.artefact!;
    expect(artefact.role).toBe('pilot-estimation');
    expect(artefact.usableForVerdict).toBe(false);
    // The TYPE is the literal `false`. If someone makes this assignable, this
    // line stops compiling — which is the guarantee, not the runtime check.
    const proof: false = artefact.usableForVerdict;
    expect(proof).toBe(false);
    expect(artefact.note).toMatch(/ESTIMATION ONLY/);
    expect(artefact.note).toMatch(/no code path sets it otherwise/);
  }, 1_800_000);

  it('measures the nuisance parameters a confirmatory design needs, each with an interval', async () => {
    const e = (artefact ?? (await runPilotEstimation()).artefact!).estimates;
    const line = (label: string, v: { value: number; interval: { low: number; high: number }; n: number }): string =>
      `  ${label.padEnd(28)} ${v.value.toFixed(4)}  [${v.interval.low.toFixed(4)}, ${v.interval.high.toFixed(4)}]  n = ${v.n}`;
    const rows = [
      line('judge tie rate (per showing)', e.judgeTieRate),
      line('both-orders consistency', e.bothOrdersConsistencyRate),
      e.decidedAgreementRate ? line('decided agreement', e.decidedAgreementRate) : '  decided agreement           NOT MEASURED (nothing was decided)',
      `  between-run ICC (rho)        ${e.betweenRunIcc ? `${e.betweenRunIcc.rho} [${e.betweenRunIcc.interval.low}, ${e.betweenRunIcc.interval.high}] over ${e.betweenRunIcc.seeds} seeds` : 'NOT MEASURED — too few seeds with 2+ decisive pairs'}`,
      `  calls per being              ${e.callsPerBeing.perBeing} (${e.callsPerBeing.completions} completions / ${e.callsPerBeing.beings} beings at ${e.callsPerBeing.ticks} ticks)`,
      `  retry rate, per arm          ${JSON.stringify(e.retryRate)}`,
      `  fallback rate, per arm       ${JSON.stringify(e.fallbackRate)}`,
      `  leak-judge calibration       ${e.leakJudgeCalibration ? 'measured' : 'NOT RUN (paid; the mock pilot never pays)'}`,
      `  integrity, per arm           ${JSON.stringify(e.integrityByArm)}`,
    ];
    // eslint-disable-next-line no-console
    console.log(['', 'ruling 1 · what the estimation pilot returns:', ...rows].join('\n'));

    // Every rate carries an interval and the n it was taken over.
    for (const v of [e.judgeTieRate, e.bothOrdersConsistencyRate]) {
      expect(v.n).toBeGreaterThan(0);
      expect(v.interval.low).toBeLessThanOrEqual(v.value);
      expect(v.interval.high).toBeGreaterThanOrEqual(v.value);
    }
    expect(e.callsPerBeing.perBeing).toBeGreaterThan(0);
    // S6 of round 4: accepted-acts-per-being travels beside the primary metric,
    // because `planSuccessRate` moves with how many impossible acts an arm pads
    // its plan with and nothing used to say so.
    for (const arm of Object.values(e.integrityByArm)) expect(arm.acceptedPerBeing).toBeGreaterThanOrEqual(0);
  }, 1_800_000);

  it('sizes the confirmatory design at the PESSIMISTIC end of every measured interval', async () => {
    const e = (artefact ?? (await runPilotEstimation()).artefact!).estimates;
    const design = designConfirmatory(e, { effect: JUDGE_GATE.declaredEffect, power: 0.8, minSeeds: MIN_PAIRED_SEEDS, costPerCall: 0.0004 });
    // eslint-disable-next-line no-console
    console.log(
      ['', 'ruling 1 · designConfirmatory(estimates, targets):',
        `  ${design.seeds} seeds x ${design.pairsPerSeed} pairs = ${design.pairs} pairs`,
        `  sized at tie ${design.sizedAtTieRate}, ICC ${design.sizedAtIcc} — power ${design.powerAtPessimistic}`,
        `  ${design.calls} calls, cost ${design.cost}; reachable ${design.reachable}`,
        `  ${design.note}`].join('\n'),
    );
    // The design is sized at the HIGH end of the tie interval, never the point.
    expect(design.sizedAtTieRate).toBeGreaterThanOrEqual(e.judgeTieRate.value);
    expect(design.sizedAtTieRate).toBeCloseTo(e.judgeTieRate.interval.high, 6);
    // Seeds, never fewer than the family correction demands.
    expect(design.seeds).toBeGreaterThanOrEqual(MIN_PAIRED_SEEDS);
    expect(design.note).toMatch(/PESSIMISTIC/);
    expect(design.note).toMatch(/OWNER'S APPROVAL/);
    // A confirmatory design at a measured tie rate does NOT fit the pilot's own
    // budget — which is the point of separating the two and the reason four
    // rounds of arithmetic kept coming out flattering.
    expect(design.calls).toBeGreaterThan(PILOT_RECIPE.budgetLimit);
  }, 1_800_000);
});
